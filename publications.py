"""Generate the CV publication lists from publications.bib.

Writes publications-first.tex and publications-other.tex, which main.tex
\\input's. The website (LouisFaure/HomePage) builds its publication pages from
the same bib, so it is the single source of truth for both.

Website-specific fields in the bib (ignored here, used by the website):
  n_cofirsts, featured, url_pdf, url_code, url_dataset, ...
`n_cofirsts` (number of co-first authors) also decides which CV list an entry
goes in: first author or one of the co-first authors -> First Author.

Usage: python3 publications.py   (needs `pip install "bibtexparser<2"`)
"""

import pathlib
import re

import bibtexparser
from bibtexparser.latexenc import latex_to_unicode

HERE = pathlib.Path(__file__).resolve().parent
ME = "Faure L."
MONTHS = "jan feb mar apr may jun jul aug sep oct nov dec".split()


def short_name(author):
    """'Kastriti, Maria Eleni' -> 'Kastriti M. E.' (same rule as the website)."""
    family, given = (p.strip() for p in latex_to_unicode(author).split(",", 1))
    return " ".join([family] + [g[0] + "." for g in given.split()])


def pub_date(entry):
    month = entry.get("month", "1")
    month = month if month.isdigit() else str(MONTHS.index(month[:3].lower()) + 1)
    return f"{entry['year']}-{month.zfill(2)}-{entry.get('day', '01').zfill(2)}"


def load(path=HERE / "publications.bib"):
    with open(path, encoding="utf-8") as f:
        entries = bibtexparser.load(f).entries
    for e in entries:
        e["authors"] = [short_name(a) for a in e["author"].split(" and ")]
        e["date"] = pub_date(e)
    return sorted(entries, key=lambda e: e["date"], reverse=True)


def is_first_author(entry):
    return entry["authors"].index(ME) < max(1, int(entry.get("n_cofirsts", 0)))


def strip_braces(s):
    return re.sub(r"(?<!\\)[{}]", "", s)


def tex_entry(entry):
    authors = entry["authors"]
    cofirsts = int(entry.get("n_cofirsts", 0))
    # Short author lists in full; long ones up to the co-first authors (at least 3), then et al.
    shown = authors if len(authors) <= 5 else authors[:max(3, cofirsts)]
    names = []
    for i, name in enumerate(shown):
        if name == ME:
            name = rf"\underline{{{name}}}"
        names.append(name + ("*" if i < cofirsts else ""))
    etal = r", \textit{et al.}" if len(shown) < len(authors) else ""
    doi = entry["doi"]
    return (
        f"{', '.join(names)}{etal} ({entry['year']}). "
        rf"\textbf{{{strip_braces(entry['title'])}}}, "
        rf"\textit{{{strip_braces(entry['journal'])}}}, "
        rf"\href{{https://doi.org/{doi}}}{{{doi.replace('_', r'\_')}}}"
    )


def write_list(path, entries):
    path.write_text(
        "% Generated by publications.py from publications.bib. Do not edit.\n"
        + "\n\\sectionsep\n\n".join(tex_entry(e) for e in entries)
        + "\n",
        encoding="utf-8",
    )


def main():
    entries = load()
    write_list(HERE / "publications-first.tex", [e for e in entries if is_first_author(e)])
    write_list(HERE / "publications-other.tex", [e for e in entries if not is_first_author(e)])


if __name__ == "__main__":
    main()
